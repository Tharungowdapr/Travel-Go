
-- SQL Schema for TravelGo (Supabase/PostgreSQL)

-- 1. Drop existing tables (in reverse order of dependencies)
DROP TABLE IF EXISTS "BOOKING" CASCADE;
DROP TABLE IF EXISTS "REVIEW" CASCADE;
DROP TABLE IF EXISTS "AVAILABILITY" CASCADE;
DROP TABLE IF EXISTS "ROOM_TYPE" CASCADE;
DROP TABLE IF EXISTS "HOTEL_IMAGE" CASCADE;
DROP TABLE IF EXISTS "HOTEL" CASCADE;
DROP TABLE IF EXISTS "CITY" CASCADE;
DROP TABLE IF EXISTS "COUNTRY" CASCADE;
DROP TABLE IF EXISTS "USER" CASCADE;

-- 2. Create tables
CREATE TABLE "USER" (
    "UserID" TEXT PRIMARY KEY,
    "UserName" TEXT UNIQUE NOT NULL,
    "FName" TEXT,
    "LName" TEXT,
    "Email" TEXT UNIQUE,
    "Password" TEXT NOT NULL,
    "Age" INTEGER,
    "Gender" TEXT,
    "Address" TEXT
);

CREATE TABLE "COUNTRY" (
    "CountryID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CountryName" TEXT UNIQUE NOT NULL
);

CREATE TABLE "CITY" (
    "CityID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CityName" TEXT NOT NULL,
    "CountryID" BIGINT REFERENCES "COUNTRY"("CountryID") ON DELETE CASCADE
);

CREATE TABLE "HOTEL" (
    "HotelID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "HotelName" TEXT NOT NULL,
    "HotelRating" INTEGER DEFAULT 0,
    "CityID" BIGINT REFERENCES "CITY"("CityID") ON DELETE CASCADE,
    "LodgingType" TEXT -- Added for AI recommendations
);

CREATE TABLE "HOTEL_IMAGE" (
    "ImageID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "HotelID" BIGINT REFERENCES "HOTEL"("HotelID") ON DELETE CASCADE,
    "HotelImage" TEXT NOT NULL
);

CREATE TABLE "ROOM_TYPE" (
    "RoomTypeID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "HotelID" BIGINT REFERENCES "HOTEL"("HotelID") ON DELETE CASCADE,
    "RoomTypeName" TEXT NOT NULL,
    "Price" DECIMAL(10, 2) NOT NULL,
    "Capacity" INTEGER DEFAULT 2
);

CREATE TABLE "AVAILABILITY" (
    "AvailabilityID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RoomTypeID" BIGINT REFERENCES "ROOM_TYPE"("RoomTypeID") ON DELETE CASCADE,
    "Date" DATE NOT NULL,
    "NumberOfRooms" INTEGER DEFAULT 10,
    UNIQUE("RoomTypeID", "Date")
);

CREATE TABLE "BOOKING" (
    "BookingID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserID" TEXT REFERENCES "USER"("UserID") ON DELETE CASCADE,
    "RoomTypeID" BIGINT REFERENCES "ROOM_TYPE"("RoomTypeID") ON DELETE CASCADE,
    "CheckinDate" DATE NOT NULL,
    "CheckoutDate" DATE NOT NULL,
    "NoOfRooms" INTEGER DEFAULT 1,
    "Confirmed" BOOLEAN DEFAULT FALSE,
    "TotalAmount" DECIMAL(10, 2)
);

CREATE TABLE "REVIEW" (
    "ReviewID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "HotelID" BIGINT REFERENCES "HOTEL"("HotelID") ON DELETE CASCADE,
    "UserID" TEXT REFERENCES "USER"("UserID") ON DELETE CASCADE,
    "Review" TEXT NOT NULL,
    "Rating" INTEGER
);
